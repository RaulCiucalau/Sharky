/**
 * Represents the keyboard input state for the game.
 * Each property corresponds to a key that can be pressed.
 */
class Keyboard {
    /**
     * Whether the left arrow key is pressed.
     * @type {boolean}
     */
    left = false;
    /**
     * Whether the right arrow key is pressed.
     * @type {boolean}
     */
    right = false;
    /**
     * Whether the spacebar is pressed.
     * @type {boolean}
     */
    space = false;
    /**
     * Whether the up arrow key is pressed.
     * @type {boolean}
     */
    up = false;
    /**
     * Whether the down arrow key is pressed.
     * @type {boolean}
     */
    down = false;
    /**
     * Whether the 'E' key is pressed.
     * @type {boolean}
     */
    E = false;
    /**
     * Whether the 'Q' key is pressed.
     * @type {boolean}
     */
    Q = false;
}